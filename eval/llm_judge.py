"""
LLM-as-judge for draft reply quality.

Scores cached support replies on:
- grounded
- relevance
- actionability
- tone

Usage:
    python -m eval.llm_judge --golden eval/golden_set/golden.jsonl
"""

import argparse
import json
import os
from pathlib import Path

from src.llm_client import complete_json


CACHE_FILE = "eval/results_cache.jsonl"

JUDGE_PROMPT = """Score this customer support reply strictly using the rubric below.

Customer message:
\"\"\"{message}\"\"\"

Draft reply:
\"\"\"{reply}\"\"\"

Rubric:

1. grounded (1-5)
How well is the reply supported by the historical evidence?
5 = strongly supported; no unsupported policy claims
1 = mostly invented or contradicted by evidence

2. relevance (1-5)
Does the reply directly address the customer's actual issue?
5 = directly addresses the issue
1 = mostly irrelevant

3. actionability (1-5)
Does the customer get a useful next step?
5 = clear and practical next step
1 = no useful action

4. tone (1-5)
Is the reply appropriate for concise brand customer support?
5 = clear, helpful and professional
1 = inappropriate, confusing or unhelpful

Return integer scores from 1 to 5.

Also provide a short explanation in overall_notes.
"""


JUDGE_SCHEMA = {
    "type": "OBJECT",
    "properties": {
        "grounded": {
            "type": "INTEGER"
        },
        "relevance": {
            "type": "INTEGER"
        },
        "actionability": {
            "type": "INTEGER"
        },
        "tone": {
            "type": "INTEGER"
        },
        "overall_notes": {
            "type": "STRING"
        },
    },
    "required": [
        "grounded",
        "relevance",
        "actionability",
        "tone",
        "overall_notes",
    ],
}


def load_jsonl(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []

    with open(path, encoding="utf-8") as f:
        return [
            json.loads(line)
            for line in f
            if line.strip()
        ]


def load_cache() -> dict[str, dict]:
    """
    Load pipeline results previously generated by eval.metrics.
    """

    records = load_jsonl(CACHE_FILE)

    return {
        item["message"]: item
        for item in records
        if "message" in item
    }


def judge_reply(
    message: str,
    reply: str,
) -> dict:
    """Score one generated reply."""

    prompt = JUDGE_PROMPT.format(
        message=message,
        reply=reply,
    )

    return complete_json(
        prompt,
        role="judge",
        max_tokens=512,
        response_schema=JUDGE_SCHEMA,
    )


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--golden",
        default="eval/golden_set/golden.jsonl",
    )

    parser.add_argument(
        "--out",
        default="eval/judge_scores.jsonl",
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=5,
        help=(
            "Maximum number of cached replies to judge. "
            "0 = judge all cached replies."
        ),
    )

    args = parser.parse_args()

    golden = load_jsonl(args.golden)

    if not golden:
        raise SystemExit(
            "No golden examples found."
        )

    cache = load_cache()

    if not cache:
        raise SystemExit(
            "No cached pipeline results found.\n"
            "Run eval.metrics first to generate "
            "cached replies."
        )

    print(
        f"Loaded {len(golden)} golden examples."
    )

    print(
        f"Loaded {len(cache)} cached pipeline results."
    )

    selected = []

    for example in golden:

        message = example[
            "customer_message"
        ]

        if message in cache:
            selected.append(example)

        if args.limit > 0 and len(selected) >= args.limit:
            break

    if not selected:
        raise SystemExit(
            "None of the golden examples have "
            "cached pipeline results."
        )

    print(
        f"\nJudging {len(selected)} cached replies."
    )

    output_path = Path(args.out)

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    scores = []

    for i, example in enumerate(
        selected,
        start=1,
    ):

        message = example[
            "customer_message"
        ]

        cached = cache[message]

        print(
            f"[{i}/{len(selected)}] "
            f"judging cached reply..."
        )

        score = judge_reply(
            message,
            cached["reply"],
        )

        record = {
            "thread_id": example[
                "thread_id"
            ],
            "customer_message": message,
            "reply": cached["reply"],
            "intent": cached.get(
                "intent"
            ),
            "escalate": cached.get(
                "escalate"
            ),
            **score,
        }

        scores.append(record)

    with open(
        output_path,
        "w",
        encoding="utf-8",
    ) as f:

        for item in scores:
            f.write(
                json.dumps(
                    item,
                    ensure_ascii=False,
                )
                + "\n"
            )

    dimensions = [
        "grounded",
        "relevance",
        "actionability",
        "tone",
    ]

    print("\n=== LLM Judge Results ===")

    for dimension in dimensions:

        values = [
            item[dimension]
            for item in scores
        ]

        average = (
            sum(values) / len(values)
        )

        print(
            f"{dimension}: "
            f"{average:.2f}/5"
        )

    print(
        f"\nSaved judge scores to: "
        f"{output_path}"
    )


if __name__ == "__main__":
    main()